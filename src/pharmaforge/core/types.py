"""Core Pydantic data schemas for molecules, tasks, skills, and verification reports."""
from __future__ import annotations

import datetime
from enum import Enum
from typing import Any
from pydantic import BaseModel, Field


class ObjectiveDirection(str, Enum):
    """Direction of optimization for a scientific property objective."""
    MINIMIZE = "minimize"
    MAXIMIZE = "maximize"


class OptimizationObjective(BaseModel):
    """Defines a target property objective with constraint boundaries."""
    name: str = Field(..., description="Property identifier (e.g., 'qed', 'logp', 'affinity', 'herg')")
    direction: ObjectiveDirection = Field(default=ObjectiveDirection.MAXIMIZE)
    threshold: float | None = Field(default=None, description="Hard boundary or target value")
    weight: float = Field(default=1.0, ge=0.0, description="Relative objective weight")
    is_hard_constraint: bool = Field(default=False, description="If true, failing threshold rejects the molecule")

    def is_satisfied(self, value: float) -> bool:
        """Check if an observed value satisfies the objective's threshold."""
        if self.threshold is None:
            return True
        if self.direction == ObjectiveDirection.MAXIMIZE:
            return value >= self.threshold
        return value <= self.threshold


class MoleculeCandidate(BaseModel):
    """Represents a generated chemical entity with calculated properties and lineage."""
    smiles: str = Field(..., description="Canonical SMILES representation")
    inchikey: str | None = Field(default=None, description="Standard InChIKey for deduplication")
    molecular_weight: float | None = Field(default=None, description="Exact molecular weight (Da)")
    logp: float | None = Field(default=None, description="Calculated octanol-water partition coefficient (logP)")
    tpsa: float | None = Field(default=None, description="Topological polar surface area (Å²)")
    qed: float | None = Field(default=None, ge=0.0, le=1.0, description="Quantitative Estimate of Drug-likeness")
    sascore: float | None = Field(default=None, description="Synthetic Accessibility Score (1.0 = easy, 10.0 = hard)")
    herg_liability: float | None = Field(default=None, description="Predicted hERG cardiotoxicity liability score (0 to 1)")
    affinity_score: float | None = Field(default=None, description="Target binding affinity (e.g. pKd / pIC50 / proxy score)")
    parent_smiles: str | None = Field(default=None, description="Source molecule SMILES prior to modification")
    transformation_applied: str | None = Field(default=None, description="Description of chemical transformation")
    metadata: dict[str, Any] = Field(default_factory=dict, description="Additional properties or execution context")

    def get_property(self, prop_name: str) -> float | None:
        """Safely retrieve a named property score."""
        if hasattr(self, prop_name):
            val = getattr(self, prop_name)
            if isinstance(val, (int, float)):
                return float(val)
        return self.metadata.get(prop_name)


class VerificationReport(BaseModel):
    """Detailed report generated by the Scientific Test-Oracle (STO-IV)."""
    is_valid: bool = Field(..., description="True if molecule passes all hard chemical and physical checks")
    passed_sanitization: bool = Field(default=False, description="RDKit Chem.SanitizeMol() status")
    passed_valence: bool = Field(default=False, description="Explicit valence and radical checks")
    passed_pains: bool = Field(default=False, description="Free of Pan-Assay Interference Compound alerts")
    passed_brenk: bool = Field(default=False, description="Free of Brenk reactive toxicophores")
    property_scores: dict[str, float] = Field(default_factory=dict, description="Computed physicochemical properties")
    error_reasons: list[str] = Field(default_factory=list, description="List of failure justifications")
    execution_time_ms: float = Field(default=0.0, description="Verification latency in milliseconds")


class ExecutionTrace(BaseModel):
    """Detailed record of a sandboxed tool or skill execution step."""
    execution_id: str = Field(..., description="Unique trace identifier")
    tool_or_skill_name: str = Field(..., description="Name of executed procedural unit")
    input_kwargs: dict[str, Any] = Field(default_factory=dict, description="Arguments passed to the code")
    stdout: str = Field(default="", description="Captured standard output")
    stderr: str = Field(default="", description="Captured standard error")
    return_value: Any = Field(default=None, description="Serialized return value")
    execution_time_seconds: float = Field(default=0.0, description="Elapsed wall-clock runtime")
    success: bool = Field(default=False, description="True if executed without unhandled exception")
    exception_type: str | None = Field(default=None, description="Exception class name if failed")
    traceback_str: str | None = Field(default=None, description="Complete formatted traceback if failed")


class ProceduralSkill(BaseModel):
    """An executable, parameter-abstracted Python procedure verified by STO-IV."""
    skill_id: str = Field(..., description="Unique skill hash identifier")
    name: str = Field(..., description="Identifier name (e.g., 'bioisostere_hydroxyl_to_fluoro')")
    description: str = Field(..., description="Natural language semantic description of skill capability")
    code: str = Field(..., description="Self-contained, executable Python function definition")
    parameters_schema: dict[str, Any] = Field(default_factory=dict, description="JSON Schema for inputs")
    return_schema: dict[str, Any] = Field(default_factory=dict, description="JSON Schema for output")
    unit_tests: str = Field(default="", description="Executable pytest/assertion block validating this skill")
    tags: list[str] = Field(default_factory=list, description="Categorization tags (e.g. ['scaffold', 'fluorination'])")
    success_count: int = Field(default=0, ge=0, description="Number of successful executions across tasks")
    failure_count: int = Field(default=0, ge=0, description="Number of execution failures")
    created_at: datetime.datetime = Field(default_factory=lambda: datetime.datetime.now(datetime.timezone.utc))
    last_repaired_at: datetime.datetime | None = Field(default=None)

    @property
    def reliability_score(self) -> float:
        """Compute the historical execution reliability score."""
        total = self.success_count + self.failure_count
        if total == 0:
            return 1.0
        return self.success_count / total


class LeadOptimizationTask(BaseModel):
    """Formal specification of a multi-objective lead optimization problem."""
    task_id: str = Field(..., description="Unique task identifier")
    target_name: str = Field(..., description="Biomedical target identifier (e.g., 'EGFR', 'DRD2')")
    target_class: str = Field(default="Unknown", description="Target protein family (e.g., 'Kinase', 'GPCR')")
    initial_smiles: str = Field(..., description="Starting lead compound SMILES")
    objectives: list[OptimizationObjective] = Field(..., description="Set of multi-objective criteria")
    max_iterations: int = Field(default=10, ge=1, description="Maximum agent optimization rounds")
    budget_tokens: int = Field(default=50000, ge=1000, description="Token consumption ceiling")
